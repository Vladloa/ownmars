export const MAP = {
  cx: 500,
  cy: 500,
  radius: 430,
};

const TIER_SIZE: Record<PlotCatalogItem["tier"], number> = {
  S: 54,
  A: 36,
  B: 24,
};

export function projectLonLat(lon: number, lat: number) {
  const { cx, cy, radius } = MAP;
  const wrapped = lon > 180 ? lon - 360 : lon;
  const x = cx + (wrapped / 180) * radius * 0.92;
  const y = cy - (lat / 90) * radius * 0.92;
  return { x, y };
}

export function hexPathForPlot(plot: PlotCatalogItem) {
  const { x, y } = projectLonLat(plot.lon, plot.lat);
  const size = TIER_SIZE[plot.tier];
  const points: string[] = [];
  for (let i = 0; i < 6; i++) {
    const angle = (Math.PI / 3) * i - Math.PI / 6;
    points.push(`${x + size * Math.cos(angle)},${y + size * Math.sin(angle)}`);
  }
  return `M ${points.join(" L ")} Z`;
}

export function centroidForPlot(plot: PlotCatalogItem) {
  return projectLonLat(plot.lon, plot.lat);
}

export function catalogBySlug(slug: string) {
  return PLOT_CATALOG.find((p) => p.slug === slug);
}
